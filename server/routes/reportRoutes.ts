import { Router } from 'express';
import { ReportModel } from '../models/Report';
import { WaterReadingModel } from '../models/WaterReading';
import { AnomalyModel } from '../models/Anomaly';
import { AlertModel } from '../models/Alert';
import { EquipmentModel } from '../models/Equipment';
import { ChemicalDosageModel } from '../models/ChemicalDosage';

const router = Router();

// List all reports
router.get('/', async (req, res) => {
  try {
    const reports = await ReportModel.find({}, { createdAt: -1 }, 30);
    return res.json({ success: true, reports });
  } catch (err: any) {
    return res.status(500).json({ success: false, message: err.message });
  }
});

// Single report details
router.get('/:id', async (req, res) => {
  try {
    const report = await ReportModel.findById(req.params.id);
    if (!report) {
      return res.status(404).json({ success: false, message: 'Report not found.' });
    }
    return res.json({ success: true, report });
  } catch (err: any) {
    return res.status(500).json({ success: false, message: err.message });
  }
});

// Generate new report
router.post('/generate', async (req, res) => {
  try {
    const { reportType = 'Daily Operational', generatedBy = 'Plant Director' } = req.body;

    const readings = await WaterReadingModel.find({}, { timestamp: -1 }, 100);
    const anomalies = await AnomalyModel.find({}, { timestamp: -1 }, 50);
    const criticalAlerts = await AlertModel.find({ severity: 'Critical' }, { timestamp: -1 }, 50);
    const equipmentItems = await EquipmentModel.find();
    const dosages = await ChemicalDosageModel.find({}, { timestamp: -1 }, 10);

    let sumPh = 0;
    let sumTurb = 0;
    let sumTemp = 0;
    let sumFlow = 0;
    let compliant = 0;

    readings.forEach((r: any) => {
      sumPh += r.ph || 7.2;
      sumTurb += r.turbidity || 1.8;
      sumTemp += r.temperature || 19.5;
      sumFlow += r.flowRate || 240;
      if (r.status === 'Normal') compliant++;
    });

    const count = readings.length || 1;
    const avgPh = Number((sumPh / count).toFixed(2));
    const avgTurbidity = Number((sumTurb / count).toFixed(2));
    const avgTemperature = Number((sumTemp / count).toFixed(1));
    const avgFlowRate = Math.round(sumFlow / count);
    const compliancePct = (compliant / count) * 100;

    let complianceStatus: 'Fully Compliant' | 'Sub-optimal' | 'Non-Compliant' = 'Fully Compliant';
    if (compliancePct < 85 || avgTurbidity > 3.0) {
      complianceStatus = 'Non-Compliant';
    } else if (compliancePct < 95 || avgTurbidity > 1.5) {
      complianceStatus = 'Sub-optimal';
    }

    const report = await ReportModel.create({
      reportTitle: `${reportType} Summary — ${new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}`,
      reportType,
      generatedBy,
      periodStart: new Date(Date.now() - 24 * 3600 * 1000),
      periodEnd: new Date(),
      summary: {
        avgPh,
        avgTurbidity,
        avgTemperature,
        avgFlowRate,
        totalTreatedVolumeM3: avgFlowRate * 24,
        anomalyCount: anomalies.length,
        criticalAlertsCount: criticalAlerts.length,
        maintenanceItemsCount: equipmentItems.filter((e: any) => e.status !== 'Operational').length,
        complianceStatus,
      },
      details: {
        equipmentSummary: equipmentItems.map((e: any) => ({
          name: e.equipmentName,
          health: e.healthScore,
          status: e.status,
          hours: e.operatingHours,
        })),
        recentDosages: dosages.map((d: any) => ({
          chemical: d.chemicalName,
          dose: d.currentDosage,
          unit: d.unit,
        })),
        readingsSampleCount: readings.length,
      },
    });

    return res.status(201).json({ success: true, report });
  } catch (err: any) {
    return res.status(500).json({ success: false, message: err.message });
  }
});

// Export report as CSV file
router.get('/:id/export-csv', async (req, res) => {
  try {
    const report = await ReportModel.findById(req.params.id);
    if (!report) {
      return res.status(404).send('Report not found');
    }

    const rows = [
      ['AquaPulse Water Treatment Plant - Certified Operational Audit'],
      ['Report ID', report._id || report.id],
      ['Title', report.reportTitle],
      ['Type', report.reportType],
      ['Generated By', report.generatedBy],
      ['Period Start', new Date(report.periodStart).toISOString()],
      ['Period End', new Date(report.periodEnd).toISOString()],
      ['Compliance Status', report.summary.complianceStatus],
      [''],
      ['Metric', 'Value', 'Unit', 'WHO Standard Range'],
      ['Average pH', report.summary.avgPh, 'pH units', '6.5 - 8.5'],
      ['Average Turbidity', report.summary.avgTurbidity, 'NTU', '< 1.0 treated (< 5.0 intake)'],
      ['Average Temperature', report.summary.avgTemperature, '°C', '10 - 25 °C'],
      ['Average Flow Rate', report.summary.avgFlowRate, 'm³/h', '120 - 450 m³/h'],
      ['Total 24h Treated Volume', report.summary.totalTreatedVolumeM3, 'm³', 'N/A'],
      ['Detected Anomalies Count', report.summary.anomalyCount, 'events', '0 ideal'],
      ['Critical Alerts Count', report.summary.criticalAlertsCount, 'alerts', '0 ideal'],
      ['Equipment Maintenance Items', report.summary.maintenanceItemsCount, 'units', '0 ideal'],
    ];

    const csvContent = rows.map((r) => r.map((c) => `"${c}"`).join(',')).join('\n');

    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', `attachment; filename="aquapulse-report-${req.params.id}.csv"`);
    return res.send(csvContent);
  } catch (err: any) {
    return res.status(500).send(err.message);
  }
});

export default router;
